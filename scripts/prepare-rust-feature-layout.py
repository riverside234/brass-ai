"""Generate native layout metadata from the immutable L01 Python oracle."""
import argparse
from dataclasses import asdict
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def generate(reference, check=False):
    baseline = json.loads((ROOT / 'artifacts/rust-backend/20261024-g890-l01-l02/baseline.json').read_text())
    pins = {f['path']: f['sha256'] for f in baseline['reference_source']['files']}
    sys.path[:0] = [str(reference / 'src')] + [str(ROOT / p) for p in
        ('artifacts/r2-pythondeps', 'artifacts/r4-pythondeps', 'artifacts/r0-pythonlibs', 'artifacts/r0-validation-deps')]
    from brass_ai.learning.features import Encoder
    from brass_ai.learning.state_layout import model_layout
    from brass_ai.learning.local_entities import entity_layout
    from brass_ai.learning.contracts import digest
    from brass_ai.feature_engineering.contracts import STATE_FIELDS, ACTION_FIELDS, STATE_INPUTS, ACTION_INPUTS
    enc = Encoder()
    for name, module in list(sys.modules.items()):
        if name.startswith('brass_ai.') and getattr(module, '__file__', None):
            path = Path(module.__file__).resolve()
            relative = path.relative_to(reference).as_posix()
            assert hashlib.sha256(path.read_bytes()).hexdigest() == pins[relative], relative
    schema = reference / 'configs/learning/features-4.0.0.json'
    assert hashlib.sha256(schema.read_bytes()).hexdigest() == pins[schema.relative_to(reference).as_posix()]
    def selection(fields, inputs):
        names = [f.name for f in fields]
        return [dict(index=names.index(f.fact), scale=f.scale, width=len(f.components)) for f in inputs]
    layout = dict(format='brass-native-feature-layout/1.0.0', schema=enc.schema,
        feature_schema_sha256=digest(enc.schema), group_layout=dict(asdict(model_layout()), identity=model_layout().identity), entity_layout=entity_layout(),
        state_inputs=selection(STATE_FIELDS, STATE_INPUTS), action_inputs=selection(ACTION_FIELDS, ACTION_INPUTS),
        source_digest=baseline['reference_source']['digest'],
        source_files=[dict(path=p, sha256=sha) for p, sha in sorted(pins.items())
                      if p.startswith(('src/brass_ai/feature_engineering/', 'src/brass_ai/learning/'))
                      or p == 'configs/learning/features-4.0.0.json'])
    path = ROOT / 'native/brass-ai-core/data/feature-layout.json'
    def publish(path, content):
        if check:
            assert path.read_text(encoding='utf-8') == content, 'Generated layout drift: '+str(path)
        else:
            path.write_text(content, encoding='utf-8')
    publish(path, json.dumps(layout, indent=2, ensure_ascii=False) + '\n')
    indices = ['// Generated by scripts/prepare-rust-feature-layout.py; semantic offsets, not fitted features.',
               '// The complete fact vocabulary is retained for audit, including omitted neural fields.',
               '#![allow(dead_code)]']
    for prefix, fields in [('S', STATE_FIELDS), ('A', ACTION_FIELDS)]:
        for i, field in enumerate(fields):
            name = field.name.replace('.', '_').upper()
            indices.append(f'pub const {prefix}_{name}: usize = {i};')
    target = ROOT / 'native/brass-ai-core/src/features/indices.rs'
    target.parent.mkdir(exist_ok=True)
    publish(target, '\n'.join(indices) + '\n')
    print(json.dumps(dict(state_dim=enc.state_dim, action_dim=enc.action_dim,
                          schema=layout['feature_schema_sha256'], source_digest=layout['source_digest'])))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--reference', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(args.reference.resolve(), args.check)
